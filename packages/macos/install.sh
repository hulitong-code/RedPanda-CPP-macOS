#!/bin/bash
# Build and install the Apple Silicon edition with locally linked Homebrew tools.
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
app_destination="$HOME/Applications/RedPandaIDE.app"
bridge_source="$root/build/lldb-mi-src"
skip_deps=0
build_only=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --app) app_destination=${2:?Missing application path}; shift 2 ;;
        --bridge-source) bridge_source=${2:?Missing source path}; shift 2 ;;
        --skip-deps) skip_deps=1; shift ;;
        --build-only) build_only=1; shift ;;
        --help) echo 'Usage: packages/macos/install.sh [--app PATH.app] [--skip-deps] [--build-only] [--bridge-source PATH]'; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; exit 2 ;;
    esac
done
[[ $(uname -s) == Darwin && $(uname -m) == arm64 ]] || { echo 'Run natively on an Apple Silicon Mac (not under Rosetta).' >&2; exit 1; }
xcrun --find clang >/dev/null 2>&1 || { echo 'Install Xcode Command Line Tools with xcode-select --install, then rerun.' >&2; exit 1; }
[[ -x /opt/homebrew/bin/brew ]] || { echo 'Install native Apple Silicon Homebrew from https://brew.sh, then rerun.' >&2; exit 1; }
export PATH="/opt/homebrew/bin:/opt/homebrew/sbin:$PATH"
if [[ $skip_deps == 0 ]]; then
    brew install cmake ninja qtbase qttools qtsvg astyle gcc@15 llvm lldb python
fi
qt_prefix=$(brew --prefix qtbase)
build="$root/build/macos"
stage="$root/build/macos-pkg"
jobs=${PANDA_BUILD_JOBS:-4}
[[ $jobs =~ ^[1-9][0-9]*$ ]] || { echo 'PANDA_BUILD_JOBS must be a positive integer.' >&2; exit 2; }
cmake -S "$root" -B "$build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_PREFIX_PATH="/opt/homebrew;$qt_prefix" -DCMAKE_OSX_ARCHITECTURES=arm64 \
    -DLUA_ADDON=ON -DVCS=ON
cmake --build "$build" --parallel "$jobs"
# Native input activity can transiently affect the Qt hover/clipboard tests.
QT_QPA_PLATFORM=offscreen ctest --test-dir "$build" --output-on-failure --repeat until-pass:2
"$root/packages/macos/build-lldb-mi.sh" "$bridge_source"
# This directory is generated by this script; do not retain obsolete plugins.
if [[ -d "$stage/RedPandaIDE.app" ]]; then
    rm -rf "$stage/RedPandaIDE.app"
fi
cmake --install "$build" --prefix "$stage"
app="$stage/RedPandaIDE.app"
"$root/packages/macos/deploy-qt.sh" "$app"
"$root/packages/macos/stage-local-tools.sh" "$app" "$bridge_source/build/src/lldb-mi"
codesign --force --deep --sign - "$app"
codesign --verify --deep --strict "$app"
# Verify the GNU header and runtime even if developer debugging is not enabled.
smoke_dir=$(mktemp -d /tmp/redpanda-install.XXXXXX)
trap 'rm -rf "$smoke_dir"' EXIT
"$app/Contents/MacOS/gcc/bin/g++" -std=c++17 -g -O0 "$root/tests/macos/bits_debug.cpp" -o "$smoke_dir/bits_debug"
"$smoke_dir/bits_debug"
if [[ $build_only == 1 ]]; then
    echo "Build verified: $app"
    exit 0
fi
[[ "$app_destination" != "$app" && "$app_destination" == /* && "$app_destination" == *.app && ! -L "$app_destination" ]] || { echo 'Use an absolute, non-symlink .app destination.' >&2; exit 2; }
if pgrep -x RedPandaIDE >/dev/null; then
    echo 'Save your work and quit Red Panda C++ before installing. The verified build is ready; rerun with --skip-deps.' >&2
    exit 1
fi
mkdir -p "$(dirname "$app_destination")"
# Keep the verified staging bundle until the replacement has been installed.
python3 "$root/packages/macos/cleanup-apps.py" --protect "$app" --destination "$app_destination" --manifest "$smoke_dir/moved.json"
ditto "$app" "$app_destination"
codesign --verify --deep --strict "$app_destination"
python3 "$root/packages/macos/seed-settings.py" --app "$app_destination" --moved-manifest "$smoke_dir/moved.json"
# Remove the generated staging bundle so only the installed version remains.
rm -rf "$app"
python3 "$root/packages/macos/cleanup-apps.py" --protect "$app_destination" --check
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$app_destination"
echo "Installed: $app_destination"
echo 'For debugging, check DevToolsSecurity -status. If disabled, enable it only with the owner’s consent: sudo DevToolsSecurity -enable'
echo 'Launch the app and use the GCC 15 Apple Silicon Debug profile. Existing settings were preserved.'
